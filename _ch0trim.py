from pathlib import Path

p = Path("00-Agent与一次调用的差别.md")
t = p.read_text(encoding="utf-8")

# 1) 六条"为什么必然"的段落 → 压成两段
start = t.index("上面六条不是经验总结，每一条都能从前面的内容推出来。")
end = t.index("六件事的代码量和")
six = t[start:end]
print("原六段长度：", len(six))

replacement = """这些不是经验总结，每一条都能从前面的内容推出来。举两个：执行只发生在调用方的代码里，能不能拦住就取决于执行是否只有一个入口——只要有两处直接调用工具函数，两处的校验就得各自维护，迟早不一致。状态只存在于内存里，进程结束就丢，要让任务继续就必须把状态写出去；写出去的时机决定重放范围，记录"打算改第 8 个文件"恢复后会再改一次，记录"已改完"恢复后才会跳过。问题不在恢复本身，在于记录的粒度没有区分意图和结果。

"""
t = t[:start] + replacement + t[end:]

# 2) harness 的两段合并压缩
old = ("""举个具体的例子。超时、重试、限流、熔断、降级这五件事看起来是五个独立功能，可以各写一个函数，但它们要读同一份状态：最近失败了几次、现在在哪个档位、冷却到什么时候。如果拆成五个互不相干的函数，这份状态就要在五个地方传来传去，或者变成全局变量——它们共享一份状态，所以必须在同一个边界内。反过来，判定"这一步做对了吗"和"没做对怎么办"看起来是两件事，但判断结果必须一致：判定说重试，修复就重试。拆开之后两边对同一个结果的理解可能不一致——它们共用同一个结论，所以也必须在同一个边界内。切分部件的依据因此是失效时它们会不会一起变，"功能像不像"不作依据。

这个定义容易读成"harness 是个万能容器"，所以要划三条线。它不改变模型的能力：换个说法写同一个提示词，模型能做的事不变，harness 里的所有内容都在处理"模型做不到什么"。它不替代工程化：沙箱、部署、监控这些即使在不用 harness 的项目里也必须做，harness 只是规定它们放在哪里、和谁相邻。它不能事后追加：如果循环没有为"中断后从哪继续"留位置，事后补不上；如果每次调用都直接写在业务代码里，事后想把超时和重试收拢也只能重写调用点。""")
new = ("""超时、重试、限流、熔断、降级看起来是五个独立功能，但它们要读同一份状态：最近失败了几次、现在在哪个档位、冷却到什么时候，拆开就得在五个地方传来传去；判定"这一步做对了吗"和"没做对怎么办"看起来是两件事，但判定说重试、修复就得重试，拆开两边对同一个结果的理解可能不一致。切分部件的依据因此是失效时它们会不会一起变。

三条线要划清。它不改变模型的能力：换个说法写同一个提示词，模型能做的事不变。它不替代工程化：沙箱、部署、监控即使不用 harness 也必须做，harness 只规定它们放在哪里。它不能事后追加：循环没有为"中断后从哪继续"留位置，事后补不上；调用直接写在业务代码里，事后想收拢超时和重试只能重写调用点。""")
assert t.count(old) == 1
t = t.replace(old, new)

# 3) 最后一段切分依据压短
old2 = """这里刻意不给 `ask`、`perform`、`record` 的实现，也不展开切分的依据。划分依据来自失效方式——决定"超时和重试该不该放在一起"，依据是它们共享同一份失败计数；决定"判定和修复该不该放在一起"，依据是它们对同一个结论的理解必须一致。这类依据只有见过它们各自怎么坏之后才能判断，在没见过之前给出一张划分表，读者只能记住表，无法推导。而且划分做错了比不做更糟：一个按错误依据切开的边界，会逼着后续每个需求去打破它或绕开它，绕开一次这层边界就失去意义了。这一节要交付的是判据，不是答案。"""
new2 = """这里不给 `ask`、`perform`、`record` 的实现，也不展开切分依据：划分依据来自失效方式，而失效方式只有见过它们各自怎么坏之后才判断得出来。这一节要交付的是判据，不是答案。"""
assert t.count(old2) == 1
t = t.replace(old2, new2)

p.write_text(t, encoding="utf-8")
print("done")
