import re
from pathlib import Path

p = Path("01-一次调用的四个字段.md")
t = p.read_text(encoding="utf-8")

# 1) 目录交给生成器
start = t.index("## 目录")
end = t.index("## 一、只取 content 的写法")
t = t[:start] + "## 目录\n\n" + t[end:]

# 2) H2 去序号、改名词短语
h2 = {
    "## 一、只取 content 的写法": "## 只取 content 的写法",
    "## 二、一次调用的往返": "## 一次调用的往返",
    "## 三、收尾原因": "## 收尾原因",
    "## 四、按取值分支": "## 按取值分支",
}
for a, b in h2.items():
    assert t.count(a) == 1, a
    t = t.replace(a, b)

# 3) H3 去章节号
h3 = {
    "### 3.1 四个取值": "### 四个取值",
    "### 3.2 取值的来历": "### 取值的来历",
    "### 3.3 stop 的含义": "### stop 的含义",
    "### 4.1 四种动作与兜底": "### 四种动作与兜底",
    "### 4.2 length 的三种补法": "### length 的三种补法",
    "### 4.3 过滤的两个来源": "### 过滤的两个来源",
    "### 4.4 参数的字符串形式": "### 参数的字符串形式",
    "### 5.2 为什么测试发现不了": "### 为什么测试发现不了",
}
for a, b in h3.items():
    assert t.count(a) == 1, a
    t = t.replace(a, b)

# 4) 第四节末尾并入「分支写错的形态」：删掉五、六两节首，压缩 5.1
i5 = t.index("## 五、四种误判")
i6 = t.index("## 六、这套分支的边界")
i7 = t.index("## 这一章建立的 6 件事")
sec5 = t[i5:i6]
sec6 = t[i6:i7]

# 5.1 的四个并列段落压成两段
body51_start = sec5.index("### 5.1 四种误判的形态")
body51_end = sec5.index("### 为什么测试发现不了")
compressed = """### 分支写错的形态

四种取值配上错误的分支，表现各不相同，其中两种几乎无法通过测试发现。截断被当成完整：代码只判断 `content` 非空，`length` 就走进成功路径，界面上显示"签收后 7 天内可退，条件是商品"这样一句语法完整、少了半句的话，不抛异常、日志没有错误、监控一切正常，唯一能发现的方式是比较 `finish_reason` 与实际使用的分支是否一致。待执行动作被当成空回答：`tool_calls` 的 `content` 是 `None`，经过 `content or ""` 变成空字符串返回，用户看到空白回答，若有重试逻辑会重试到上限再报"模型无响应"，真实原因是没执行工具并把结果送回去。

被拦截当成长度问题：拦截返回空字符串，若分支写成"内容为空就重试"，会反复重试一个不会成功的结果，更糟的是切换降级模型——被拦的是内容，不是模型。新取值落进成功路径：用 `if/elif` 写四种取值却不写 `else`，厂商新增取值时代码走完全部判断继续向下，落进"正常处理"，这与截断一样安静。`branches.py` 的兜底返回 `("未知", "未处理的取值：...")` 而不是"接受"，是有意为之：新增取值应当被人看见，而不是被猜。

"""

sec5_new = compressed + sec5[body51_end:]

# 6.1、6.2 保留改题，6.3 压缩为一段，6.4 删除
s61 = sec6.index("### 6.1 四类回答不了的问题")
s62 = sec6.index("### 6.2 单次生成与整轮任务")
s63 = sec6.index("### 6.3 两个上限")
s64 = sec6.index("### 6.4 一次调用与一次计费")

p61 = sec6[s61:s62].split("\n", 1)[1].strip()
p62 = sec6[s62:s63].split("\n", 1)[1].strip()
p63 = sec6[s63:s64]

# 6.3 只留一段结论，两个上限的数值表放在第 3 章
p63_keep = """### 两个上限

`max_tokens` 与上下文窗口是两个不同的限制，混淆它们会导致一类特定失败：请求在生成开始之前就被拒绝，而代码把它当成生成失败去重试。`max_tokens` 是预留量，不是产出量——请求时说"最多允许生成 256 个"，实际可能只生成 9 个，但窗口按预留算，服务端需要在生成开始前确认输入加上限放得下。所以窗口溢出的判据是"输入 + 预留输出 > 窗口"，与这次实际生成了多少无关。`length` 是生成中途被掐断，能拿到部分文本；窗口溢出是生成根本没开始，拿不到响应体。数值对照与动态上限的算法在第 3 章。
"""

sec_border = "\n".join([
    "### 适用范围",
    p61,
    "",
    p62,
    "",
    p63_keep,
])

# 组装：第四节 = 4.x 内容 + 分支写错的形态 + 为什么测试发现不了 + 区分表 + 适用范围
t = t[:i5 - 0] + sec5_new + sec_border + "\n\n" + t[i7:]

# 5.3 标题去掉（它现在在第四节里作为最后一张表）——先看是否存在
if "### 5.3 四种误判的区分" in t:
    t = t.replace("### 5.3 四种误判的区分", "### 四种误判的区分")

p.write_text(t, encoding="utf-8")
print("H2:", re.findall(r"(?m)^## (.+)$", t))
