body7 = sec7.split("\n", 1)[1].strip()
# 去掉 七 里的示意账单与表，只保留报账三行的口径结论
body7_keep = body7

# 六：只留分词、模板、单价、窗口四条；换个形式压成一段，并入成本结构末尾
p6 = """换一家厂商，这一章的数会跟着变，变的方式不一样。分词器与词表变了，同一段中文的 token 数就不同；模板开销变了，`usage` 与本地 content 的差就不同；单价与缓存结构变了，同一个 `usage` 算出不同的钱；窗口大小与是否共享变了，溢出点就换位置。隔离这四件事只有三种手段，按强度从低到高：配置化（价格表、窗口、模型名写进配置）、能力探测（启动时跑一次探测请求，失败即降级）、适配层（统一字段名与错误码，但不统一数值）。最容易出错的是拿 A 厂商的分词结果乘 B 厂商的单价：账单对不上时两边各自都是对的，唯一可靠的做法是让 `usage` 与价格表在同一个作用域里相乘。适配层的边界也只有一条，统一形状不统一数值——token 数、价格、缓存比例必须原样透传，谁给的数就记在谁头上。
"""

# 八：只留三条真结论，并入「溢出之后的三条路」的末尾
