"""第 1 章 step3：幻觉是怎么产生的——三种"依据情况"，三种回答（离线）。

运行：
    python code/ch01_llm_basics/step3_hallucination.py

上一级的痛点：知道窗口有限，但不知道"没有依据时它会怎样"。

这一级做什么：用一个"有没有依据"的判据，模拟三种提问，
然后对比"模型的回答"和"真实依据"，量化它有多自信地编。

本脚本的"模型"是规则实现（离线可跑）。它的目的不是模仿 GPT 的措辞，
而是把"依据不足 → 硬答"这个机制**显式地摆出来**，让你看清幻觉的根。
"""
from __future__ import annotations

# "语料"：模型训练时见过的东西（这里用一份政策手册模拟）
CORPUS = """
签收后 7 天内，商品未拆封且不影响二次销售的，可申请无理由退货。
定制类商品、生鲜类商品、已激活的数码产品不适用无理由退货。
签收后 15 天内出现非人为损坏的质量问题，可申请换新或退货。
"""

# 问题 → (依据片段 | None, 模型"续写"出来的回答)
CASES = [
    ("退款要几天？", "签收后 7 天内", "签收后 7 天内可以申请无理由退货。"),
    ("退货运费谁承担？", None, "退货运费由买家承担，质量问题除外。"),
    ("耳机能退吗？", "已激活的数码产品不适用", "只要不影响二次销售就可以退货。"),
    ("会员退货优惠券返还吗？", None, "优惠券会原路返还到您的账户。"),
    ("客服电话是多少？", None, "您可以拨打 400-800-1234 咨询。"),
]


def grounded(answer: str, evidence: str | None) -> str:
    """粗校验：回答里的关键片段能不能在依据里找到。"""
    if evidence is None:
        return "❌ 无依据"
    # 只看前 8 个字是否出现在依据里（教学用，真实系统要更严格）
    return "✅ 有依据" if answer[:8] in evidence else "⚠️ 部分"


def main() -> None:
    print("=" * 84)
    print("五类问题：依据在不在，和它答得有多像真的")
    print("=" * 84)
    print(f"{'问题':<22}{'依据':<14}{'回答':<34}{'校验'}")
    print("-" * 84)
    for q, evidence, answer in CASES:
        tag = "有" if evidence else "无"
        print(f"{q:<22}{tag:<14}{answer:<34}{grounded(answer, evidence)}")

    print("-" * 84)
    no_ev = [c for c in CASES if c[1] is None]
    print(f"无依据时它仍然给出了完整回答：{len(no_ev)}/{len(CASES)} 次")
    print(f"其中被粗校验判为「有依据」的：{sum(1 for c in no_ev if grounded(c[2], c[1]) == '✅ 有依据')} 次")

    print("\n" + "=" * 84)
    print("为什么它不会说「不知道」")
    print("=" * 84)
    print("  因为它的任务是「接着往下写」，而「客服回答退货问题」这个位置上，")
    print("  最像的下文就是一句**具体的政策描述**——不是「我不确定」。")
    print()
    print("  换句话说：")
    print("    · 有依据时 → 它复述依据（但可能复述错）")
    print("    · 无依据时 → 它按「最像的回答」生成（这就是幻觉）")
    print("    · **两种情况的语气完全一样**，人无法从措辞上分辨")

    print("\n" + "=" * 84)
    print("三种防线，成本从低到高")
    print("=" * 84)
    rows = [
        ("提示词约束", "在 prompt 里写「资料里没有就说不知道」", "低", "不总是有效"),
        ("RAG", "先检索依据，再让模型基于依据回答", "中", "需要建索引"),
        ("回答后校验", "逐句核对「这句话在不在依据里」", "高", "多一次调用"),
    ]
    print(f"  {'手段':<12}{'怎么做':<40}{'成本':<6}代价")
    print("  " + "-" * 78)
    for name, how, cost, cost2 in rows:
        print(f"  {name:<12}{how:<40}{cost:<6}{cost2}")

    print("\n" + "=" * 84)
    print("结论")
    print("=" * 84)
    print("  · 幻觉不是「模型坏了」，是「没有依据时它也会接着写」。")
    print("  · 靠提示词只能降低概率，不能消除——必须让**依据**进上下文。")
    print("  · 所以下一步是：先把「依据从哪来」搞清楚（第 8–10 章 RAG），")
    print("    再谈「怎么判断它答得对不对」（第 43 章评测）。")
    print()
    print("  最后一条：**语气不能作为可信度的信号。**")
    print("  它编造时和复述时的语气一模一样——这也是为什么必须有校验。")


if __name__ == "__main__":
    main()
