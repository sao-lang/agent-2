"""一次实体消歧错误：两家“远山科技”被合并。"""

from __future__ import annotations

def main() -> None:
    docs = [
        ("c1", "远山科技（苏州）是云海集团的供应商。", "远山科技"),
        ("c2", "远山科技（深圳）是蓝湖资本的客户。", "远山科技"),
        ("c3", "远山科技（苏州）供应工业传感器。", "远山科技"),
    ]
    print("抽取结果（规则替身把括号里的地名丢了）:")
    for chunk, text, entity in docs:
        print(f"  {chunk}: {text} -> e:{entity}")

    print("\n图里的错误：")
    print("  e:远山科技 --供应商--> 云海集团")
    print("  e:远山科技 --客户----> 蓝湖资本")
    print("  e:远山科技 --供应----> 工业传感器")

    print("\n查询：蓝湖资本的客户给云海集团供应什么？")
    print("错误答案：工业传感器")
    print("实际：蓝湖资本的客户是深圳远山，它不供应；供应的是苏州远山。")
    print("根因：实体消歧把两个不同主体并成了一个节点。")


if __name__ == "__main__":
    main()
