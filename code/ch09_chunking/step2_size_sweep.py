def embed(text: str, dim: int = 128) -> list[float]:
    v = [0.0] * dim
    t = text.replace(" ", "").replace("\n", "")
    for i in range(max(1, len(t) - 2)):
        g = t[i : i + 3]
        h = 0
        for ch in g:
            h = (h * 131 + ord(ch)) % 1_000_003
        v[h % dim] += 1.0
    n = math.sqrt(sum(x * x for x in v)) or 1.0
    return [x / n for x in v]


def cos(a: list[float], b: list[float]) -> float:
    return sum(x * y for x, y in zip(a, b))


def evaluate(size: int, overlap: int, k: int = 3) -> tuple[float, int, float]:
    """返回 (Recall@k, 块数, 平均块长)。"""
    chunks = split_fixed(LONG_DOC, size=size, overlap=overlap)
    if not chunks:
        return 0.0, 0, 0.0
    vecs = [embed(c) for c in chunks]

    hit = 0
    for q, fact in QUERIES:
        # **正确答案必须完整落在某一块里**，否则再怎么检索也答不出
        gold_idx = [i for i, c in enumerate(chunks) if fact in c]
        if not gold_idx:
            continue  # 被切断 → 计为未命中
        qv = embed(q)
        ranked = sorted(range(len(chunks)), key=lambda i: -cos(qv, vecs[i]))[:k]
        if any(i in gold_idx for i in ranked):
            hit += 1
    return hit / len(QUERIES), len(chunks), sum(len(c) for c in chunks) / len(chunks)


def intact_rate(size: int, overlap: int) -> float:
    """答案片段有多少比例没被切断。"""
    chunks = split_fixed(LONG_DOC, size=size, overlap=overlap)
    ok = sum(1 for _, fact in QUERIES if any(fact in c for c in chunks))
    return ok / len(QUERIES)


